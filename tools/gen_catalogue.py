#!/usr/bin/env python3
"""Generate demo/catalogue.lua: the uiMap catalogue C_Map would give Atlas,
from a game version's own UiMap.db2 and UiMapAssignment.db2, so the web demo
can run Atlas.Scan over fake readers (demo/readers.lua).

  python3 tools/gen_catalogue.py local "/Applications/World of Warcraft" wow_classic_beta \\
      -o demo/catalogue.lua
"""
from __future__ import annotations

import argparse
import struct
import sys

from mmtools.db2 import read_wdc5
from mmtools.log import log
from mmtools.luaout import lua_str
from mmtools.sources import Source, add_source_args, source_from_args

UIMAP_DB2 = 1957206             # dbfilesclient/uimap.db2
UIMAPASSIGNMENT_DB2 = 1957219   # dbfilesclient/uimapassignment.db2

# UiMap fields (row[0] is the record index; the ID is inline):
#   Name_lang, ID, ParentUiMapID, Flags, System, Type, ...
# UiMapAssignment fields:
#   UiMin[2], UiMax[2], Region[6] (minX, minY, minZ, maxX, maxY, maxZ),
#   ID, UiMapID, OrderIndex, MapID, AreaID, ...
# Region X is north, Y is west (UnitPosition's axes).


def f32(v: int) -> float:
    return struct.unpack("<f", struct.pack("<I", v))[0]


def read_catalogue(src: Source) -> dict[int, dict]:
    maps = {}
    for r in read_wdc5(src.read(UIMAP_DB2), string_fields={0}):
        maps[r[2]] = {"name": r[1], "type": r[6], "parent": r[3], "assign": []}
    rows = read_wdc5(src.read(UIMAPASSIGNMENT_DB2))
    for r in sorted(rows, key=lambda r: (r[5], r[6], r[4])):
        ui_min, ui_max, region = [f32(v) for v in r[1]], [f32(v) for v in r[2]], [f32(v) for v in r[3]]
        maps[r[5]]["assign"].append({
            "inst": r[7], "ui": ui_min + ui_max,
            "north": (region[0], region[3]), "west": (region[1], region[4]),
        })
    return maps


def num(v: float) -> str:
    return f"{v:.2f}".rstrip("0").rstrip(".")


def write_catalogue(out, src: Source, maps: dict[int, dict]) -> None:
    w = out.write
    w(f"-- GENERATED by tools/gen_catalogue.py from the {src.product} {src.version} UiMap and UiMapAssignment tables. Do not edit.\n")
    w("-- maps[uiMapID] = { name, mapType (Enum.UIMapType), parent, assign = { ... } }\n")
    w("-- assign: { inst, x0, y0, x1, y1 (normalized rect of the uiMap), north0, north1, west0, west1 (world yards) },\n")
    w("--   in OrderIndex order; the rect's top-left is (north1, west1), bottom-right (north0, west0)\n")
    w(f"MagicMap_Catalogue = {{ product = \"{src.product}\", version = \"{src.version}\", maps = {{\n")
    for mid in sorted(maps):
        m = maps[mid]
        assigns = ", ".join(
            "{ " + ", ".join([str(a["inst"])] + [num(v) for v in (*a["ui"], *a["north"], *a["west"])]) + " }"
            for a in m["assign"])
        w(f"  [{mid}] = {{ name = {lua_str(m['name'])}, mapType = {m['type']}, parent = {m['parent']}, "
          f"assign = {{ {assigns} }} }},\n")
    w("} }\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_source_args(parser)
    parser.add_argument("-o", "--output", default="-")
    ns = parser.parse_args()
    src = source_from_args(parser, ns)
    maps = read_catalogue(src)
    log(f"{len(maps)} uiMaps, {sum(len(m['assign']) for m in maps.values())} assignments")
    out = sys.stdout if ns.output == "-" else open(ns.output, "w")
    write_catalogue(out, src, maps)


if __name__ == "__main__":
    main()
