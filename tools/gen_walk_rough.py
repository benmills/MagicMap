#!/usr/bin/env python3
"""Data/WalkRough.lua: where a route's drawn line may not cut across. Each terrain chunk's 8 x 8 quads (~4 yd). A
quad is rough when one of its triangles (the game's: 4 a quad, round its centre) is too steep to walk up (over 50 degrees, gen_walk's STEEP and WALL) and taller than the game's 2-yd step, or has no
ground (a terrain hole: a building's or a cave's footprint). Deep water isn't rough: you swim it.

The search finds its way by parts (Data/Walk.lua, WalkParts.lua); this is only for drawing it: straightening and
rounding keep the line off rough quads (atlas/Route.lua).

  .venv/bin/python tools/gen_walk_rough.py --cache DIR -o Data/WalkRough.lua

--cache: gen_walk's terrain cache (fine_<inst>.npz, written by `tools/gen_walk.py --cache DIR`).
"""
import argparse
import math
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import gen_walk as gw  # noqa: E402
from mmtools.luaout import data_head  # noqa: E402

STEP = 2.0  # yd: the game steps up this much whatever the slope
MAPS = {0: "Eastern Kingdoms", 1: "Kalimdor"}  # (the open-world continents routes are drawn on)


def ch(v: int) -> str:
    return chr(48 + v)


BITS = 6  # a char's bits
NCH = (64 + BITS - 1) // BITS  # chars for a chunk's 64 quads (11)


def rough_tiles(fine: dict) -> dict[int, str]:
    """{tile key: chunks' records}: per chunk with a rough quad, its index (iy * 16 + ix; 2 chars) and its 64 quads'
    bits (qy * 8 + qx; 11 chars of 6 bits, low first), then the same for its sheer quads (a wall face taller than the
    step, or a hole: not even walking down crosses them; a steep one, 50 to 61.6 degrees, you walk down), in chunk
    order."""
    F = gw.Fine(fine)
    tri = np.stack([F.P, F.Q, F.M], -1)
    span = tri.max(-1) - tri.min(-1)  # [n, 256]: each triangle's height from its lowest corner to its highest
    k = F.kind
    hole = (k == gw.HOLE) & ((F.QK.reshape(F.n, 64)[:, np.arange(256) // 4] & gw.Q_NONE) == 0)
    bad = ((k == gw.STEEP) | (k == gw.WALL)) & (span > STEP) | hole
    sheer = (k == gw.WALL) & (span > STEP) | hole  # not even down: a fall, or no ground
    quads = bad.reshape(F.n, 64, 4).any(-1)  # [n, qy * 8 + qx]
    walls = sheer.reshape(F.n, 64, 4).any(-1)
    out: dict[int, list] = {}

    def enc(q):
        bits = int(sum(1 << b for b in range(64) if q[b]))
        return "".join(ch(bits >> (BITS * c) & 63) for c in range(NCH))
    for j in np.nonzero(quads.any(1))[0]:
        gc, gr = int(F.gc[j]), int(F.gr[j])
        key, i = (gc // 16) * 64 + gr // 16, (gr % 16) * 16 + gc % 16
        out.setdefault(key, []).append((i, ch(i // 64) + ch(i % 64) + enc(quads[j]) + enc(walls[j])))
    return {k: "".join(s for _, s in sorted(v)) for k, v in out.items()}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cache", required=True)
    ap.add_argument("-o", "--output", required=True)
    ns = ap.parse_args()
    with open(ns.output, "w", encoding="utf-8", newline="\n") as out:
        out.write("-- GENERATED by tools/gen_walk_rough.py from gen_walk's terrain cache. Do not edit.\n")
        out.write("-- WalkRough[inst][col * 64 + row] = the tile's chunks with a rough quad (8 x 8 quads of ~4 yd a chunk: too steep\n")
        out.write("--   to walk over, or a terrain hole), in chunk order: 24 chars each, chr(48 + v): the chunk's index (iy * 16 + ix)\n")
        out.write("--   as 2, its rough quads' bits (qy * 8 + qx) as 11 of 6 bits, low first, then its sheer ones' (over 61.6 degrees\n")
        out.write("--   or a hole: not even walked down) as 11. For drawing a route's line (atlas/Route.lua).\n")
        out.write(data_head("WalkRough"))
        out.write("D.WalkRough = {\n")
        for inst, name in MAPS.items():
            path = os.path.join(ns.cache, f"fine_{inst}.npz")
            if not os.path.exists(path):
                continue
            with np.load(path) as z:
                tiles = rough_tiles({k: z[k] for k in z.files})
            out.write(f"  [{inst}] = {{ -- {name}\n")
            for key in sorted(tiles):
                s = tiles[key].replace("\\", "\\\\")
                out.write(f'    [{key}] = "{s}",\n')
            out.write("  },\n")
            print(f"[{inst}] {name}: {len(tiles)} tiles, {sum(len(s) for s in tiles.values()) // (2 + 2 * NCH)} chunks", file=sys.stderr)
        out.write("}\n")


if __name__ == "__main__":
    main()
