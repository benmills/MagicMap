#!/usr/bin/env python3
"""Generate Data/AreaGrid.lua: the AreaTable ID of every terrain chunk.

Every ADT tile is split into 16x16 chunks (~33 yards) and each chunk (MCNK)
records its AreaTable ID: the game's own answer to "which zone / subzone is
this spot in". Per tile we write a palette of the area IDs it uses and the
256 chunks as palette letters, run-length coded like Data/Walk.lua.

  python3 tools/gen_areagrid.py local "/Applications/World of Warcraft" wow_classic_beta \\
      -o Data/AreaGrid.lua

Output is deterministic: the same game data always gives the same file.
"""
from __future__ import annotations

import argparse
import string
import sys

from mmtools.formats import adt_chunks, wdt_maid
from mmtools.log import log
from mmtools.luaout import run_letters
from mmtools.maps import MAP_DB2, read_maps
from mmtools.sources import add_source_args, source_from_args

LETTERS = string.ascii_lowercase + string.ascii_uppercase  # palette index 1..52


def encode_tile(adt: bytes) -> tuple[list[int], str]:
    """(palette, cells) for one tile; chunks missing from the ADT are area 0."""
    areas = [0] * 256
    for ch in adt_chunks(adt):
        areas[ch.iy * 16 + ch.ix] = ch.area
    palette = list(dict.fromkeys(areas))
    if len(palette) > len(LETTERS):
        raise SystemExit(f"tile needs {len(palette)} palette entries (max {len(LETTERS)})")
    index = {a: LETTERS[i] for i, a in enumerate(palette)}
    return palette, run_letters([index[a] for a in areas])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_source_args(parser)
    parser.add_argument("-o", "--output", help="output file (default: stdout)")
    ns = parser.parse_args()
    src = source_from_args(parser, ns)

    src.prefetch([MAP_DB2])
    map_db2 = src.read(MAP_DB2)
    if map_db2 is None:
        raise SystemExit("Map.db2 not available")
    maps = read_maps(map_db2)
    src.prefetch(m.wdt for m in maps)

    out = open(ns.output, "w", encoding="utf-8", newline="\n") if ns.output else sys.stdout
    w = out.write
    w(f"-- GENERATED by tools/gen_areagrid.py from the {src.product} {src.version} terrain (ADT chunk areas). Do not edit.\n")
    w("-- [inst][col * 64 + row] = { palette (areaIDs, 0 = none), cells }: the tile's 16x16 chunks (iy * 16 + ix),\n")
    w("--   each a letter a..z A..Z = palette index 1..52, a run as the letter and its length\n")
    w("MagicMap_AreaGrid = {\n")
    for m in sorted(maps, key=lambda m: m.inst):
        wdt = src.read(m.wdt)
        if wdt is None:
            continue
        adts = {k: t.root_adt for k, t in wdt_maid(wdt).items() if t.root_adt}
        if not adts:
            continue
        src.prefetch(adts.values())
        rows, widest = [], 0
        for key in sorted(adts):
            buf = src.read(adts[key])
            if buf is None:
                continue
            palette, cells = encode_tile(buf)
            widest = max(widest, len(palette))
            rows.append(f"    [{key}] = {{ {{ {', '.join(map(str, palette))} }}, \"{cells}\" }},\n")
        if not rows:
            continue
        log("%s: [%d] %s: %d tiles, palette up to %d" % (src.product, m.inst, m.name, len(rows), widest))
        name = m.name.replace("\n", " ")
        w(f"  [{m.inst}] = {{ -- {name}\n")
        w("".join(rows))
        w("  },\n")
    w("}\n")
    if out is not sys.stdout:
        out.close()


if __name__ == "__main__":
    main()
