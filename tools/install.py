#!/usr/bin/env python3
"""Install this checkout into a WoW client for testing: replaces
<wow>/<flavor>/Interface/AddOns/MagicMap with what the game loads
(MagicMap.toc, the files it lists and the Textures/ tree), straight from
the working tree, so uncommitted changes are included. /reload in game to pick up Lua changes;
a file the client hasn't seen (a new file, texture or the folder itself) needs a
client restart: it says so (spike-bugs L5).

The spike's own MagicMap folder (its TOC saves MagicMapDB) is never replaced
unless --replace-spike, which moves it to MagicMap.spike-backup first. The
spike's saved data isn't read (D9, docs/decisions/0007-v2-storage-names.md).

The TOC is generated, first: HEADER, then each folder's files.txt in MANIFESTS
order (docs/structure.md "Load order"). A new file goes in its folder's
files.txt; tools/luacheck.py fails while the committed TOC differs.

  python3 tools/install.py                    # _classic_beta_ (WoW Forever)
  python3 tools/install.py _classic_ptr_      # another flavor folder
  python3 tools/install.py --wow "D:/Games/World of Warcraft"
  python3 tools/install.py --toc              # only write MagicMap.toc
  python3 tools/install.py --replace-spike    # the spike's MagicMap moved to MagicMap.spike-backup first

The WoW folder defaults to $MAGICMAP_WOW, else the standard install location.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from luacheck import existing_toc_files, toc_files  # noqa: E402

ADDON = "MagicMap"
SAVED = "MagicMap2DB"  # D9: not the spike's MagicMapDB (ADR 0007)
TOC = os.path.join(ROOT, f"{ADDON}.toc")
BACKUP = f"{ADDON}.spike-backup"
HEADER = f"""## Interface: 16001
## Title: MagicMap
## Notes: For WoW Forever. Your minimap, zooming out to the whole world on the game's own minimap terrain, with Blizzard's blips on it; M grows it into a big map.
## Version: 2.0.0-rc.1
## X-License: GPL-3.0-only
## Category: Map & Minimap
## IconTexture: Interface\\Icons\\INV_Misc_Map_01
## AddonCompartmentFunc: MagicMap_OnAddonCompartmentClick
## SavedVariables: {SAVED}

# GENERATED by tools/install.py from each folder's files.txt (load order: docs/structure.md). Do not edit:
# list a file in its folder's files.txt, then tools/install.py --toc.
runtime\\Boot.lua
"""
# Each folder's manifest, in load order: (heading, files.txt). Boot.lua (HEADER) marks the load start.
MANIFESTS = [
    ("Atlas", "atlas/files.txt"),
    ("Runtime", "runtime/files.txt"),
    ("Model (before Game, which hands it observations and its saved part)", "model/files.txt"),
    ("Game", "game/files.txt"),
    ("Game: commands (Game.Handle)", "game/commands/files.txt"),
    ("Game: observation parts (Game.Part)", "game/parts/files.txt"),
    ("UI", "ui/files.txt"),
]
DEFAULT_WOW = {
    "darwin": "/Applications/World of Warcraft",
    "win32": r"C:\Program Files (x86)\World of Warcraft",
}


def texture_files() -> list[str]:
    out = []
    for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, "Textures")):
        dirnames.sort()
        out += [os.path.relpath(os.path.join(dirpath, f), ROOT) for f in sorted(filenames) if not f.startswith(".")]
    return out


def toc() -> str:
    """The TOC the manifests make."""
    out = [HEADER]
    for heading, manifest in MANIFESTS:
        with open(os.path.join(ROOT, manifest), encoding="utf-8") as f:
            files = f.read().split()
        out.append(f"\n# {heading}\n" + "".join(p.replace("/", "\\") + "\n" for p in files))
    return "".join(out)


def write_toc() -> bool:
    """MagicMap.toc from the manifests; True if it changed."""
    text = toc()
    with open(TOC, encoding="utf-8") as f:
        if f.read() == text:
            return False
    with open(TOC, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    return True


def stamp_version(toc: str, rev: str) -> None:
    """An installed or packaged TOC's ## Version: becomes the build's (docs/telemetry.md), and ## X-Stamped:
    with it (game/Validate.lua's one build's log: a TOC without it is "unstamped")."""
    with open(toc, encoding="utf-8") as f:
        lines = f.read().splitlines(keepends=True)
    with open(toc, "w", encoding="utf-8", newline="") as f:
        f.writelines(f"## Version: {rev}\n## X-Stamped: {rev}\n" if line.startswith("## Version:") else line
                     for line in lines)


def toc_field(toc: str, field: str) -> str:
    with open(toc, encoding="utf-8-sig", errors="replace") as f:
        return next((line.split(":", 1)[1].strip() for line in f if line.startswith(f"## {field}:")), "")


def saved_variables(toc: str) -> str:
    return toc_field(toc, "SavedVariables")


def title(toc: str) -> str:
    return toc_field(toc, "Title")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("flavor", nargs="?", default="_classic_beta_", help="flavor folder (default: _classic_beta_)")
    parser.add_argument("--wow", default=os.environ.get("MAGICMAP_WOW") or DEFAULT_WOW.get(sys.platform),
                        help="World of Warcraft folder (default: $MAGICMAP_WOW or the standard location)")
    parser.add_argument("--no-check", action="store_true", help="skip the Lua check before installing")
    parser.add_argument("--toc", action="store_true", help="only write MagicMap.toc from the manifests")
    parser.add_argument("--stamp", nargs=2, metavar=("TOC", "REV"), help="only stamp that TOC as build REV (tools/package.sh)")
    parser.add_argument("--replace-spike", action="store_true",
                        help=f"move the spike's {ADDON} folder to {BACKUP} first (else its being there stops the install)")
    ns = parser.parse_args()
    if ns.stamp:
        stamp_version(*ns.stamp)
        return

    if write_toc():
        print(f"{ADDON}.toc: written from the manifests (commit it)")
    if ns.toc:
        return

    addons = os.path.join(ns.wow or "", ns.flavor, "Interface", "AddOns")
    if not os.path.isdir(addons):
        sys.exit(f"no {addons}; pass --wow / a flavor folder (has this flavor been run once?)")
    if not ns.no_check and subprocess.call([sys.executable, os.path.join(ROOT, "tools", "luacheck.py")],
                                           stdout=subprocess.DEVNULL) != 0:
        sys.exit("luacheck found problems (tools/luacheck.py); not installing. --no-check to install anyway")

    listed = existing_toc_files()
    skipped = sorted(set(toc_files()) - set(listed))
    files = [f"{ADDON}.toc"] + listed + texture_files()
    missing = [f for f in files if not os.path.isfile(os.path.join(ROOT, f))]
    if missing:
        sys.exit(f"missing from the checkout: {', '.join(missing)}")

    dest = os.path.join(addons, ADDON)
    if os.path.islink(dest):
        sys.exit(f"{dest} is a symlink (already points at a checkout); remove it first if you want a copy")
    old = os.path.join(dest, f"{ADDON}.toc")
    if os.path.exists(dest) and not os.path.isfile(old):  # only ever delete our own
        sys.exit(f"{dest} doesn't look like {ADDON} (no {ADDON}.toc); not deleting it")
    if os.path.exists(dest) and saved_variables(old) != SAVED:
        backup = os.path.join(addons, BACKUP)
        if not ns.replace_spike:
            sys.exit(f"{dest} is the spike (it saves {saved_variables(old)}): --replace-spike moves it to {backup}"
                     " first (its saved data isn't read: D9)")
        if os.path.exists(backup):
            sys.exit(f"{backup} is there already: move it away first")
        shutil.move(dest, backup)
        print(f"the spike's {dest} moved to {backup}")
    before = set()  # what the client may have seen: a file new to it needs a restart (spike-bugs L5)
    for dirpath, _, filenames in os.walk(dest):
        before |= {os.path.relpath(os.path.join(dirpath, f), dest).replace(os.sep, "/") for f in filenames}
    if os.path.exists(dest):
        shutil.rmtree(dest)
    for f in files:
        target = os.path.join(dest, f)
        os.makedirs(os.path.dirname(target), exist_ok=True)
        shutil.copy2(os.path.join(ROOT, f), target)

    try:
        rev = subprocess.check_output(["git", "-C", ROOT, "describe", "--always", "--dirty"], text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        rev = "?"
    # The files installed, named: uncommitted changes (git can't see them) make a build of their own
    # (game/Validate.lua keeps one build's log).
    digest = hashlib.sha1()
    for f in files:
        with open(os.path.join(ROOT, f), "rb") as fh:
            digest.update(f.encode() + b"\0" + fh.read())
    rev += "." + digest.hexdigest()[:7]
    stamp_version(os.path.join(dest, f"{ADDON}.toc"), rev)
    print(f"installed {ADDON} {rev} ({len(files)} files) into {dest}")
    if skipped:
        print(f"missing, so left out: {', '.join(skipped)} (tools/gen_questie.py)")
    added = [f for f in files if f not in before]
    if added:
        print(f"restart the client (not /reload): {len(added)} files are new to it ({', '.join(added[:3])}"
              f"{', ...' if len(added) > 3 else ''}); /mm lists the commands")
    else:
        print("/reload in game; /mm lists the commands")
    for name in sorted(os.listdir(addons)):  # an older build under another folder loads too
        other = os.path.join(addons, name, f"{name}.toc")
        if name != ADDON and os.path.isfile(other) and title(other).startswith(ADDON):
            print(f"{os.path.join(addons, name)} ({title(other)}) loads too: turn it off in the AddOns list")


if __name__ == "__main__":
    main()
