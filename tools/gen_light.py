#!/usr/bin/env python3
"""Generate Data/Light.lua: the game's outdoor lighting by place and time of day, for the map's
time-of-day tint (ui/Tint.lua), as WoW Forever tints its own minimap.

For every open-world map Data/Tiles.lua lists: its lights (Light.db2), each with its centre in
tiles, its falloff start and end in tiles and its clear-weather params (the first LightParamsID);
the one with no place and no falloff is the map's default. Per params used, its day (LightData.db2)
as time (half-minutes, 0-2880), DirectColor, AmbientColor and Forever's own colour column
(Field_1_60_1_69876_055), packed 0xRRGGBB.

  python3 tools/gen_light.py local "/Applications/World of Warcraft" wowf -o Data/Light.lua

Deterministic.
"""
from __future__ import annotations

import argparse
import os
import re

from mmtools.dbd import read_table
from mmtools.log import log
from mmtools.luaout import data_head
from mmtools.sources import add_source_args, source_from_args

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIGHT_DB2, LIGHT_DATA_DB2 = 1375579, 1375580
TILE = 1600 / 3
FOREVER = "Field_1_60_1_69876_055"


def open_world_insts(path: str) -> set[int]:
    with open(path, encoding="utf-8") as f:
        return {int(m.group(1)) for m in re.finditer(r"^  \[(\d+)\] = \{ name = .*$", f.read(), re.M)
                if "kind =" not in m.group(0)}


def fmt(v: float) -> str:
    return ("%.3f" % v).rstrip("0").rstrip(".")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_source_args(ap)
    ap.add_argument("-o", "--output", default=os.path.join(ROOT, "Data", "Light.lua"))
    ns = ap.parse_args()
    src = source_from_args(ap, ns)
    insts = open_world_insts(os.path.join(ROOT, "Data", "Tiles.lua"))
    lights = read_table("Light", src.read(LIGHT_DB2))
    days = read_table("LightData", src.read(LIGHT_DATA_DB2))

    maps, used = {}, set()
    for l in sorted(lights, key=lambda l: l["ID"]):
        inst = l["ContinentID"]
        if inst not in insts:
            continue
        pid = l["LightParamsID"][0] & 0xffff  # u16[8] read as u32s: the first is clear weather
        if not pid:
            continue
        m = maps.setdefault(inst, {"default": None, "lights": []})
        x, y, _ = l["GameCoords"]
        if l["GameFalloffEnd"] == 0 and x == 0 and y == 0:
            m["default"] = pid
        else:
            m["lights"].append((32 - y / TILE, 32 - x / TILE, l["GameFalloffStart"] / TILE, l["GameFalloffEnd"] / TILE, pid, l["ID"]))
        used.add(pid)

    curves = {}
    for d in days:
        if d["LightParamID"] in used:
            curves.setdefault(d["LightParamID"], []).append(
                (d["Time"] & 0xffff, d["DirectColor"] & 0xffffff, d["AmbientColor"] & 0xffffff, d[FOREVER] & 0xffffff))

    out = open(ns.output, "w", encoding="utf-8", newline="\n")
    w = out.write
    w("-- GENERATED by tools/gen_light.py from Light.db2 and LightData.db2: do not edit.\n")
    w("-- [inst] = { default = params, lights = { { col, row, falloff start, falloff end (tiles), params }, ... } };\n")
    w("-- params[id] = { time (half-minutes), direct, ambient, forever (0xRRGGBB), ... } through the day.\n")
    w(data_head("Light"))
    w("D.Light = {\n  maps = {\n")
    for inst in sorted(maps):
        m = maps[inst]
        w(f"    [{inst}] = {{ default = {m['default'] or 'nil'}, lights = {{\n")
        for col, row, a, b, pid, lid in m["lights"]:
            w(f"      {{ {fmt(col)}, {fmt(row)}, {fmt(a)}, {fmt(b)}, {pid} }}, -- {lid}\n")
        w("    } },\n")
    w("  },\n  params = {\n")
    n = 0
    for pid in sorted(curves):
        rows = sorted(set(curves[pid]))
        n += len(rows)
        w(f"    [{pid}] = {{ " + ", ".join("%d, 0x%06x, 0x%06x, 0x%06x" % r for r in rows) + " },\n")
    w("  },\n}\n")
    out.close()
    log("%d maps, %d lights, %d params, %d keys, %d KB" % (
        len(maps), sum(len(m["lights"]) for m in maps.values()), len(curves), n, os.path.getsize(ns.output) // 1024))


if __name__ == "__main__":
    main()
