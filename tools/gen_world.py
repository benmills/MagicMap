#!/usr/bin/env python3
"""Generate the DB2-derived Atlas data: Data/UiMaps.lua, Data/Areas.lua,
Data/Places.lua and Data/ItemIcons.lua (see docs/atlas-data.md), from a game
build's own tables. Columns are named by the WoWDBDefs layouts in tools/dbd/.

  python3 tools/gen_world.py local "/Applications/World of Warcraft" wow_classic_beta -o Data

ItemIcons has the items Data/Items.lua keeps (tools/gen_questie.py, which reads
UiMaps from here): on a new build run this, gen_questie, then this again.

Positions are projected from world yards (X north, Y west) into tile space.
Flight points (and POIs the table gives no area) take their areaID from the
ADT chunk under them.
"""
from __future__ import annotations

import argparse
import os
import re

import lupa.lua51 as lupa

from mmtools.dbd import read_table
from mmtools.formats import adt_chunks, wdt_maid
from mmtools.log import log
from mmtools.luaout import data_head, load_data, lua_str
from mmtools.sources import Source, add_source_args, source_from_args

FDIDS = {
    "AreaTable": 1353545, "TaxiNodes": 1068100, "TaxiPath": 1067802, "AreaPOI": 1000630,
    "UiMap": 1957206, "UiMapAssignment": 1957219, "Map": 1349477, "MapDifficulty": 1367868,
    "DungeonEncounter": 1347279, "Item": 841626,
}
TILE_YARDS = 1600 / 3
WORLD_MAP = 1                     # Enum.UIMapType.World: spans instances
KINDS = {1: "dungeon", 2: "raid", 3: "battleground"}  # Map.InstanceType
NO_AREA = (0, -1)                 # AreaPOI.AreaID unset (65535 read as int16)


def tile(north: float, west: float) -> tuple[float, float]:
    return 32 - west / TILE_YARDS, 32 - north / TILE_YARDS


def faction(alliance: bool, horde: bool) -> str | None:
    return ("A" if alliance else "") + ("H" if horde else "") or None


def lua(v) -> str:
    if v is None:
        return "nil"
    if isinstance(v, str):
        return lua_str(v)
    if isinstance(v, float):
        s = f"{v:.3f}".rstrip("0").rstrip(".")
        return "0" if s == "-0" else s
    if isinstance(v, (list, tuple)):
        return "{ " + ", ".join(lua(x) for x in v) + " }" if v else "{}"
    return str(v)


def row(vals: list) -> str:
    while vals and vals[-1] is None:
        vals = vals[:-1]
    return lua(vals)


class Terrain:
    """The area ID of the ADT chunk at a tile-space point, per instance."""

    def __init__(self, src: Source, wdts: dict[int, int]):
        self.src, self.wdts, self.adts, self.chunks = src, wdts, {}, {}

    def area(self, inst: int, col: float, row_: float) -> int | None:
        if inst not in self.adts:
            wdt = self.src.read(self.wdts[inst]) if self.wdts.get(inst) else None
            self.adts[inst] = {k: t.root_adt for k, t in wdt_maid(wdt).items() if t.root_adt} if wdt else {}
        key = int(col) * 64 + int(row_)
        fdid = self.adts[inst].get(key)
        if fdid is None:
            return None
        if fdid not in self.chunks:
            buf = self.src.read(fdid)
            self.chunks[fdid] = {(c.ix, c.iy): c.area for c in adt_chunks(buf)} if buf else {}
        area = self.chunks[fdid].get((int(col % 1 * 16), int(row_ % 1 * 16)))
        return area or None


def header(w, src: Source, tables: str, layout: str) -> None:
    w(f"-- GENERATED by tools/gen_world.py from the {src.product} {src.version} {tables}. Do not edit.\n")
    w(layout)


def write_uimaps(path: str, src: Source, t: dict) -> int:
    assigns = {}
    for a in sorted(t["UiMapAssignment"], key=lambda a: (a["OrderIndex"], a["ID"])):
        assigns.setdefault(a["UiMapID"], a)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        w = f.write
        header(w, src, "UiMap and UiMapAssignment tables",
               "-- [uiMapID] = { name, mapType (Enum.UIMapType), parent, inst, col0, row0, col1, row1, areaID }\n"
               "-- rect (tile space, top-left to bottom-right) from the first assignment; world maps: no inst/rect\n")
        w(data_head("UiMaps"))
        w("D.UiMaps = {\n")
        for m in sorted(t["UiMap"], key=lambda m: m["ID"]):
            a = assigns.get(m["ID"])
            vals = [m["Name_lang"], m["Type"], m["ParentUiMapID"] or None]
            if a and m["Type"] != WORLD_MAP:
                # The region covers [UiMin, UiMax] of the map: stretch it to the map's 0..1.
                min_n, min_w, _, max_n, max_w, _ = a["Region"]
                c_a, r_a = tile(max_n, max_w)
                c_b, r_b = tile(min_n, min_w)
                (ux0, uy0), (ux1, uy1) = a["UiMin"], a["UiMax"]
                sc, sr = (c_b - c_a) / (ux1 - ux0), (r_b - r_a) / (uy1 - uy0)
                assert sc > 0 and sr > 0, f"uiMap {m['ID']}: an empty rect (Atlas.TileToMap divides by its sides)"
                vals += [a["MapID"], c_a - ux0 * sc, r_a - uy0 * sr, c_a + (1 - ux0) * sc, r_a + (1 - uy0) * sr,
                         a["AreaID"] or None]
            w(f"  [{m['ID']}] = {row(vals)},\n")
        w("}\n")
    return len(t["UiMap"])


def write_areas(path: str, src: Source, t: dict) -> int:
    areas = {a["ID"]: a for a in t["AreaTable"]}
    named = {}
    for a in sorted(t["UiMapAssignment"], key=lambda a: (a["OrderIndex"], a["ID"])):
        if a["AreaID"]:
            named.setdefault(a["AreaID"], a["UiMapID"])

    def ui_map(aid: int, seen=()) -> int | None:
        if aid in named or aid not in areas or aid in seen:
            return named.get(aid)
        return ui_map(areas[aid]["ParentAreaID"], seen + (aid,))

    with open(path, "w", encoding="utf-8", newline="\n") as f:
        w = f.write
        header(w, src, "AreaTable and UiMapAssignment tables",
               "-- [areaID] = { name, parent (nil: zone), inst, level (ExplorationLevel), faction, uiMap }\n")
        w(data_head("Areas"))
        w("D.Areas = {\n")
        for aid in sorted(areas):
            a = areas[aid]
            mask = a["FactionGroupMask"]
            w(f"  [{aid}] = {row([a['AreaName_lang'], a['ParentAreaID'] or None, a['ContinentID'], a['ExplorationLevel'], faction(mask & 2, mask & 4), ui_map(aid)])},\n")
        w("}\n")
    return len(areas)


def write_places(path: str, src: Source, t: dict) -> dict:
    maps = {m["ID"]: m for m in t["Map"]}
    terrain = Terrain(src, {i: m["WdtFileDataID"] for i, m in maps.items()})
    counts = {}
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        w = f.write
        header(w, src, "TaxiNodes, TaxiPath, AreaPOI, Map, MapDifficulty and DungeonEncounter tables",
               "-- flight[nodeID] = { name, faction, inst, col, row, areaID }\n"
               "-- taxiPaths = { { from, to, cost }, ... }\n"
               "-- pois[poiID] = { name, description, icon, importance, inst, col, row, areaID }\n"
               "-- dungeons[instID] = { name, kind, entranceInst, col, row, minLevel, maxPlayers, bosses }\n")
        w(data_head("Places"))
        w("D.Places = {\n  flight = {\n")
        nodes = sorted(t["TaxiNodes"], key=lambda n: n["ID"])
        for n in nodes:
            col, rw = tile(n["Pos"][0], n["Pos"][1])
            inst = n["ContinentID"]
            w(f"    [{n['ID']}] = {row([n['Name_lang'], faction(n['Flags'] & 1, n['Flags'] & 2), inst, col, rw, terrain.area(inst, col, rw)])},\n")
        counts["flight"] = len(nodes)
        w("  },\n  taxiPaths = {\n")
        paths = sorted(t["TaxiPath"], key=lambda p: p["ID"])
        for p in paths:
            w(f"    {row([p['FromTaxiNode'], p['ToTaxiNode'], p['Cost']])},\n")
        counts["taxiPaths"] = len(paths)
        w("  },\n  pois = {\n")
        pois = sorted(t["AreaPOI"], key=lambda p: p["ID"])
        for p in pois:
            col, rw = tile(p["Pos"][0], p["Pos"][1])
            inst = p["ContinentID"]
            area = p["AreaID"] if p["AreaID"] not in NO_AREA else terrain.area(inst, col, rw)
            w(f"    [{p['ID']}] = {row([p['Name_lang'], p['Description_lang'] or None, p['Icon'], p['Importance'], inst, col, rw, area])},\n")
        counts["pois"] = len(pois)
        w("  },\n  dungeons = {\n")
        levels, bosses = {}, {}
        for d in t["MapDifficulty"]:
            m = re.search(r"at least level (\d+)", d["Message_lang"])
            if m:
                levels[d["MapID"]] = min(int(m[1]), levels.get(d["MapID"], 999))
        for e in sorted(t["DungeonEncounter"], key=lambda e: (e["OrderIndex"], e["ID"])):
            names = bosses.setdefault(e["MapID"], [])
            if e["Name_lang"] not in names:
                names.append(e["Name_lang"])
        dungeons = [m for m in sorted(maps.values(), key=lambda m: m["ID"]) if m["InstanceType"] in KINDS]
        for m in dungeons:
            entrance = [None, None, None]
            if m["CorpseMapID"] >= 0 and any(m["Corpse"]):
                entrance = [m["CorpseMapID"], *tile(m["Corpse"][0], m["Corpse"][1])]
            w(f"    [{m['ID']}] = {row([m['MapName_lang'], KINDS[m['InstanceType']], *entrance, levels.get(m['ID']), m['MaxPlayers'] or None, bosses.get(m['ID'])])},\n")
        counts["dungeons"] = len(dungeons)
        w("  },\n}\n")
    return counts


def quest_items(path: str) -> set[int]:
    """The item IDs Data/Items.lua keeps (tools/gen_questie.py: the items quests reach, D3)."""
    return set(load_data(lupa.LuaRuntime(), path).Data.Items.keys())


def write_item_icons(path: str, src: Source, t: dict, keep: set[int]) -> int:
    items = sorted((i["ID"], i["IconFileDataID"]) for i in t["Item"] if i["IconFileDataID"] and i["ID"] in keep)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        w = f.write
        header(w, src, "Item table", "-- [itemID] = iconFileDataID, for the items in Data/Items.lua (those quests reach)\n")
        w(data_head("ItemIcons"))
        w("D.ItemIcons = {\n")
        for iid, icon in items:
            w(f"  [{iid}] = {icon},\n")
        w("}\n")
    return len(items)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_source_args(parser)
    parser.add_argument("-o", "--out-dir", default="Data")
    parser.add_argument("--items", default="Data/Items.lua", help="ItemIcons keeps its items (none there: not written)")
    ns = parser.parse_args()
    src = source_from_args(parser, ns)
    src.prefetch(FDIDS.values())
    t = {name: read_table(name, src.read(fdid)) for name, fdid in FDIDS.items()}
    out = ns.out_dir
    log(f"UiMaps: {write_uimaps(os.path.join(out, 'UiMaps.lua'), src, t)}")
    log(f"Areas: {write_areas(os.path.join(out, 'Areas.lua'), src, t)}")
    log(f"Places: {write_places(os.path.join(out, 'Places.lua'), src, t)}")
    if os.path.exists(ns.items):
        log(f"ItemIcons: {write_item_icons(os.path.join(out, 'ItemIcons.lua'), src, t, quest_items(ns.items))}")
    else:
        log(f"ItemIcons: not written, no {ns.items} (tools/gen_questie.py, then this again)")


if __name__ == "__main__":
    main()
